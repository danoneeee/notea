package notes

import teanotesv1 "notea/api/proto/teanotes/v1"

func descriptor(id, name string) *teanotesv1.Descriptor {
	return &teanotesv1.Descriptor{
		Id:       id,
		Name:     name,
		Type:     teanotesv1.DescriptorType_DESCRIPTOR_TYPE_BOTH,
		ColorHex: "",
	}
}

func segment(id, name string, descriptors ...*teanotesv1.Descriptor) *teanotesv1.DescriptorSegment {
	return &teanotesv1.DescriptorSegment{
		Id:          id,
		Name:        name,
		Descriptors: descriptors,
	}
}

func family(id, name, color string, segments ...*teanotesv1.DescriptorSegment) *teanotesv1.DescriptorCategory {
	return &teanotesv1.DescriptorCategory{
		Id:       id,
		Name:     name,
		ColorHex: color,
		Segments: segments,
	}
}

